-- Historial de bajas de socios con el motivo, para ver por qué se van.
-- Queda aunque el socio se reactive o se elimine (por eso se guarda también el nombre).
CREATE TABLE IF NOT EXISTS public.bajas_socios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id bigint REFERENCES public.socios(id) ON DELETE SET NULL,
    socio_nombre character varying(255) NOT NULL,
    fecha timestamp(6) without time zone NOT NULL,
    motivo character varying(40) NOT NULL,
    detalle text,
    registrado_por character varying(100)
);
CREATE INDEX IF NOT EXISTS ix_bajas_socios_socio ON public.bajas_socios (socio_id);
CREATE INDEX IF NOT EXISTS ix_bajas_socios_fecha ON public.bajas_socios (fecha);
