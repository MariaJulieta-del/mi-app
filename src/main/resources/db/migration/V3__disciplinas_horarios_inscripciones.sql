-- Disciplinas: horarios por día, varias disciplinas por socio, color e instructor vinculado.

-- 1) Horarios: cada clase tiene su día y su franja (ej. Yoga lunes 09:00 y miércoles 19:00)
CREATE TABLE IF NOT EXISTS public.disciplina_horarios (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id bigint NOT NULL REFERENCES public.disciplinas(id) ON DELETE CASCADE,
    dia           character varying(10) NOT NULL,
    hora_inicio   character varying(5)  NOT NULL,
    hora_fin      character varying(5)  NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_disciplina_horarios_disciplina ON public.disciplina_horarios (disciplina_id);

-- Pasa el horario único anterior (mismos horarios para todos los días marcados)
INSERT INTO public.disciplina_horarios (disciplina_id, dia, hora_inicio, hora_fin)
SELECT d.id, dd.dia, d.hora_inicio, d.hora_fin
FROM public.disciplinas d
JOIN public.disciplina_dias dd ON dd.disciplina_id = d.id
WHERE coalesce(d.hora_inicio, '') <> '' AND coalesce(d.hora_fin, '') <> ''
  AND NOT EXISTS (SELECT 1 FROM public.disciplina_horarios h WHERE h.disciplina_id = d.id);

-- 2) Inscripciones: un socio puede estar en varias disciplinas
CREATE TABLE IF NOT EXISTS public.disciplina_inscripciones (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id bigint NOT NULL REFERENCES public.disciplinas(id) ON DELETE CASCADE,
    socio_id      bigint NOT NULL REFERENCES public.socios(id) ON DELETE CASCADE,
    fecha_alta    date   NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT ux_disciplina_inscripciones UNIQUE (disciplina_id, socio_id)
);
CREATE INDEX IF NOT EXISTS ix_disciplina_inscripciones_socio ON public.disciplina_inscripciones (socio_id);

-- Pasa la disciplina única que tenía cada socio
INSERT INTO public.disciplina_inscripciones (disciplina_id, socio_id)
SELECT disciplina_id, id FROM public.socios WHERE disciplina_id IS NOT NULL
ON CONFLICT DO NOTHING;

-- 3) Color (1 a 8, de la paleta de la app) e instructor vinculado a un profesor
ALTER TABLE public.disciplinas ADD COLUMN IF NOT EXISTS color integer;
ALTER TABLE public.disciplinas ADD COLUMN IF NOT EXISTS profesor_id bigint REFERENCES public.usuarios(id) ON DELETE SET NULL;

-- Colores iniciales en orden, para que las disciplinas existentes no queden todas iguales
UPDATE public.disciplinas d SET color = x.n
FROM (SELECT id, ((row_number() OVER (ORDER BY id) - 1) % 8) + 1 AS n FROM public.disciplinas) x
WHERE x.id = d.id AND d.color IS NULL;

