-- ── Entrenamiento ───────────────────────────────────────────────────────────
-- Superseries: los ejercicios seguidos con el mismo número se hacen alternando series
ALTER TABLE public.rutina_ejercicios ADD COLUMN IF NOT EXISTS superserie integer;
-- Esfuerzo percibido del ejercicio ese día (1 a 10)
ALTER TABLE public.progreso_ejercicio ADD COLUMN IF NOT EXISTS rpe smallint;
-- El socio elige aparecer en el ranking del mes
ALTER TABLE public.socios ADD COLUMN IF NOT EXISTS ranking_visible boolean NOT NULL DEFAULT false;

-- Cada entrenamiento terminado, con lo que el socio le cuenta al profe
CREATE TABLE IF NOT EXISTS public.sesiones_entrenamiento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id bigint NOT NULL REFERENCES public.socios(id) ON DELETE CASCADE,
    rutina_id bigint REFERENCES public.rutinas(id) ON DELETE SET NULL,
    rutina_nombre character varying(255),
    dia integer,
    fecha date NOT NULL,
    duracion_min integer,
    series integer,
    volumen_kg numeric(12,1),
    records integer NOT NULL DEFAULT 0,
    sensacion character varying(20),
    comentario text,
    leida boolean NOT NULL DEFAULT false,
    creada timestamp(6) without time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_sesiones_socio ON public.sesiones_entrenamiento (socio_id, fecha);
CREATE INDEX IF NOT EXISTS ix_sesiones_fecha ON public.sesiones_entrenamiento (fecha);

-- ── Reservas de clases (por fecha y horario) ────────────────────────────────
CREATE TABLE IF NOT EXISTS public.reservas_clase (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id bigint NOT NULL REFERENCES public.disciplinas(id) ON DELETE CASCADE,
    socio_id bigint NOT NULL REFERENCES public.socios(id) ON DELETE CASCADE,
    fecha date NOT NULL,
    hora_inicio character varying(5) NOT NULL,
    -- CONFIRMADA, ESPERA, CANCELADA, LIBERADA (alumno fijo que avisa que no va), ASISTIO, AUSENTE
    estado character varying(20) NOT NULL,
    creada timestamp(6) without time zone NOT NULL,
    actualizada timestamp(6) without time zone,
    CONSTRAINT uq_reserva_clase UNIQUE (disciplina_id, socio_id, fecha, hora_inicio)
);
CREATE INDEX IF NOT EXISTS ix_reservas_clase ON public.reservas_clase (disciplina_id, fecha, hora_inicio);
CREATE INDEX IF NOT EXISTS ix_reservas_socio ON public.reservas_clase (socio_id, fecha);

-- ── Retención: tareas automáticas para no perder socios ─────────────────────
CREATE TABLE IF NOT EXISTS public.acciones_retencion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id bigint NOT NULL REFERENCES public.socios(id) ON DELETE CASCADE,
    tipo character varying(30) NOT NULL,
    -- PENDIENTE (para el staff), HECHA, DESCARTADA, AUTOMATICA (aviso enviado en la app)
    estado character varying(15) NOT NULL,
    mensaje text,
    creada timestamp(6) without time zone NOT NULL,
    resuelta timestamp(6) without time zone,
    resuelta_por character varying(100)
);
CREATE INDEX IF NOT EXISTS ix_retencion_socio ON public.acciones_retencion (socio_id, tipo);
CREATE INDEX IF NOT EXISTS ix_retencion_estado ON public.acciones_retencion (estado);
