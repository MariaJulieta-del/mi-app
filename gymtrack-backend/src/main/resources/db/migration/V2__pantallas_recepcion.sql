-- Pantallas fijas de recepción (tablet/monitor con el QR de ingreso).
-- Su token solo permite ver el QR vigente y los últimos ingresos.
CREATE TABLE IF NOT EXISTS public.dispositivos_kiosco (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      character varying(60) NOT NULL,
    creado      timestamp(6) without time zone NOT NULL,
    creado_por  character varying(50),
    activo      boolean NOT NULL,
    ultimo_uso  timestamp(6) without time zone
);
